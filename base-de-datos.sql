-- 1) CATÁLOGO DE EQUIPOS -------------------------------------------------
create table if not exists public.equipos (
  id               bigint generated by default as identity primary key,
  orden            int          not null default 0,      -- orden en que aparece en la web
  activo           boolean      not null default true,   -- false = se oculta de la web
  imagen           text,                                  -- ruta, ej. media/equipos/event-26a.jpg
  categoria        text         not null,
  tipo             text         not null,
  marca            text         not null default 'Por definir',
  modelo           text         not null,
  nombre           text         not null,
  descripcion      text         not null default '',
  especificaciones jsonb        not null default '[]'::jsonb,  -- lista de textos
  ficha_pendiente  boolean      not null default false,
  precio           numeric(10,2),                         -- null = "Precio por consultar"
  cantidad         int          not null default 0,       -- unidades disponibles
  icono            text,
  creado           timestamptz  not null default now()
);

-- 2) SOLICITUDES DE COTIZACIÓN -------------------------------------------
create table if not exists public.solicitudes (
  id             uuid        primary key default gen_random_uuid(),
  creado         timestamptz not null default now(),
  estado         text        not null default 'nueva',   -- nueva / contactado / cotizado / cerrado
  nombre         text        not null,
  telefono       text        not null,
  correo         text        not null,
  tipo_evento    text        not null,
  fecha_evento   date        not null,
  lugar          text        not null,
  mensaje        text        not null default '',
  notas_internas text        not null default ''
);

create table if not exists public.solicitud_items (
  id             bigint generated by default as identity primary key,
  solicitud_id   uuid   not null references public.solicitudes(id) on delete cascade,
  equipo_id      bigint references public.equipos(id) on delete set null,
  nombre_equipo  text   not null,                         -- copia del nombre al momento de pedir
  cantidad       int    not null check (cantidad between 1 and 999)
);
create index if not exists solicitud_items_solicitud_idx on public.solicitud_items(solicitud_id);

-- 3) SEGURIDAD (Row Level Security) ---------------------------------------
-- Visitantes de la web: solo pueden LEER equipos activos y ENVIAR solicitudes
-- mediante la función crear_solicitud. No pueden leer ni modificar solicitudes.
alter table public.equipos          enable row level security;
alter table public.solicitudes      enable row level security;
alter table public.solicitud_items  enable row level security;

revoke all on public.equipos, public.solicitudes, public.solicitud_items from anon, authenticated;
grant select on public.equipos to anon, authenticated;

drop policy if exists "Catalogo publico" on public.equipos;
create policy "Catalogo publico" on public.equipos
  for select to anon, authenticated
  using (activo = true);
-- (solicitudes y solicitud_items no tienen políticas: nadie desde la web puede tocarlas)

-- 4) FUNCIÓN QUE RECIBE LA SOLICITUD DESDE LA WEB -------------------------
create or replace function public.crear_solicitud(
  p_nombre text, p_telefono text, p_correo text, p_tipo_evento text,
  p_fecha_evento date, p_lugar text, p_mensaje text, p_items jsonb
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  if length(trim(coalesce(p_nombre, ''))) < 2 or length(p_nombre) > 120 then
    raise exception 'Nombre inválido';
  end if;
  if length(trim(coalesce(p_telefono, ''))) < 6 or length(p_telefono) > 40 then
    raise exception 'Teléfono inválido';
  end if;
  if p_correo is null or length(p_correo) > 160 or p_correo !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'Correo inválido';
  end if;
  if length(trim(coalesce(p_tipo_evento, ''))) < 2 or length(p_tipo_evento) > 60 then
    raise exception 'Tipo de evento inválido';
  end if;
  if p_fecha_evento is null or p_fecha_evento < current_date - 1 then
    raise exception 'Fecha inválida';
  end if;
  if length(trim(coalesce(p_lugar, ''))) < 2 or length(p_lugar) > 200 then
    raise exception 'Lugar inválido';
  end if;
  if length(coalesce(p_mensaje, '')) > 2000 then
    raise exception 'Mensaje demasiado largo';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) not between 1 and 60 then
    raise exception 'Equipos inválidos';
  end if;

  insert into public.solicitudes (nombre, telefono, correo, tipo_evento, fecha_evento, lugar, mensaje)
  values (trim(p_nombre), trim(p_telefono), trim(p_correo), trim(p_tipo_evento),
          p_fecha_evento, trim(p_lugar), coalesce(p_mensaje, ''))
  returning id into v_id;

  insert into public.solicitud_items (solicitud_id, equipo_id, nombre_equipo, cantidad)
  select v_id, e.id, e.nombre, least(greatest((i->>'cantidad')::int, 1), 999)
  from jsonb_array_elements(p_items) as i
  join public.equipos e on e.id = (i->>'id')::bigint and e.activo;

  if not exists (select 1 from public.solicitud_items where solicitud_id = v_id) then
    raise exception 'Ningún equipo válido en la solicitud';
  end if;

  return v_id;
end;
$$;

revoke all on function public.crear_solicitud(text, text, text, text, date, text, text, jsonb) from public;
grant execute on function public.crear_solicitud(text, text, text, text, date, text, text, jsonb) to anon, authenticated;

